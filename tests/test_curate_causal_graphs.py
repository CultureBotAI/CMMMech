def test_order_record_keys_places_causal_graphs_before_history(record):
    misordered = {
        "history_refs": ["history/records/synthetic-material/2026-01-01T000000Z-curator-abcdef.yaml"],
        "curation_history": [
            {
                "timestamp": "2026-01-01T00:00:00Z",
                "curator": "curator",
                "action": "create",
                "summary": "Initial creation.",
            }
        ],
        "id": record["id"],
        "name": record["name"],
        "material_kind": record["material_kind"],
        "description": record["description"],
        "sources": record["sources"],
        "mechanisms": record["mechanisms"],
        "causal_graphs": _sample_patch()["causal_graphs"],
        "ima_symbol": "Aka",
        "polymorph_or_grade": "3C-SiC",
    }
    ordered = curate_mod.order_record_keys(misordered)
    keys = list(ordered.keys())
    assert keys.index("ima_symbol") == keys.index("material_kind") + 1
    assert keys.index("polymorph_or_grade") == keys.index("ima_symbol") + 1
    assert keys.index("causal_graphs") == keys.index("mechanisms") + 1
    assert keys.index("curation_history") == keys.index("causal_graphs") + 1
    assert keys.index("history_refs") == keys.index("curation_history") + 1


def test_curate_record_file_applies_patch_and_mints_history(tmp_path, record):
    rec_dir = tmp_path / "data" / "records"
    rec_dir.mkdir(parents=True)
    slug = record["id"].split(":", 1)[1]
    rec_path = rec_dir / f"{slug}.yaml"
    rec_path.write_text(yaml.safe_dump(record, sort_keys=False), encoding="utf-8")

    patch_path = tmp_path / "patch.yaml"
    patch_path.write_text(yaml.safe_dump(_sample_patch(), sort_keys=False), encoding="utf-8")

    rc = curate_mod.main(
        [
            str(rec_path),
            "--repo-root",
            str(tmp_path),
            "--patch",
            str(patch_path),
            "--summary",
            "Ground Gdh protein example and add solubilization causal graph.",
            "--details",
            "Added UniProtKB:P27175 protein example and gdh_solubilization_pathway causal graph.",
            "--actor-name",
            "marcin",
            "--actor-type",
            "ai_agent",
            "--model",
            "claude-opus-4-6",
            "--agent-tool",
            "antigravity",
            "--issue",
            "#808",
        ]
    )
    assert rc == 0

    updated = read_record(rec_path)
    assert validate_record(updated) == []
    assert validate_references(updated, rec_path, tmp_path) == []

    keys = list(updated.keys())
    assert keys.index("causal_graphs") < keys.index("curation_history")
    assert keys.index("curation_history") < keys.index("history_refs")

    mech_keys = list(updated["mechanisms"][0].keys())
    assert mech_keys.index("protein_examples") < mech_keys.index("evidence")

    assert len(updated["history_refs"]) == 1
    sidecar_rel = updated["history_refs"][0]
    sidecar_data, problems = read_history(tmp_path / sidecar_rel, tmp_path)
    assert problems == []
    assert sidecar_data["events"][0]["type"] == "EDIT"
    assert "causal_graphs" in sidecar_data["events"][0]["sections"]


def test_curate_record_file_rejects_invalid_patch_without_side_effects(tmp_path, record):
    rec_dir = tmp_path / "data" / "records"
    rec_dir.mkdir(parents=True)
    slug = record["id"].split(":", 1)[1]
    rec_path = rec_dir / f"{slug}.yaml"
    original_text = yaml.safe_dump(record, sort_keys=False)
    rec_path.write_text(original_text, encoding="utf-8")

    bad_patch = _sample_patch()
    bad_patch["causal_graphs"][0]["edges"][0]["predicate"] = "not_a_valid_predicate"

    with pytest.raises(ValueError, match="Record validation failed before write"):
        curate_mod.curate_record_file(
            rec_path,
            repo_root=tmp_path,
            patch=bad_patch,
            summary="Should fail",
            details="Invalid predicate must be rejected before minting history.",
        )

    assert rec_path.read_text(encoding="utf-8") == original_text
    assert not (tmp_path / "history").exists()


def test_apply_curation_patch_supports_mechanism_field_patches(record):
    mech_id = record["mechanisms"][0]["id"]
    first_patch, sections = curate_mod.apply_curation_patch(
        record,
        {
            "mechanism_organisms": {
                mech_id: [
                    {
                        "id": "NCBITaxon:272562",
                        "label": "Clostridium acetobutylicum ATCC 824",
                    }
                ]
            },
            "mechanism_evidence": {
                mech_id: [
                    {
                        "source_ref": "fixture",
                        "supports": "support",
                        "explanation": "Mechanism evidence upsert via mechanism_evidence patch.",
                    }
                ]
            },
            "mechanism_observations": {
                mech_id: [
                    {
                        "parameter": "operating_ph",
                        "value": "5.5",
                        "unit": "pH",
                        "notes": "Upserted mechanism observation.",
                    }
                ]
            },
        },
    )
    assert "mechanisms" in sections
    mech = first_patch["mechanisms"][0]
    assert any(org.get("id") == "NCBITaxon:272562" for org in mech["organisms"])
    assert any(
        ev.get("explanation") == "Mechanism evidence upsert via mechanism_evidence patch."
        for ev in mech["evidence"]
    )
    assert any(obs.get("parameter") == "operating_ph" for obs in mech["observations"])

    replaced, _ = curate_mod.apply_curation_patch(
        first_patch,
        {
            "mechanism_patches": {
                mech_id: {
                    "replace_observations": True,
                    "observations": [
                        {
                            "parameter": "temperature",
                            "value": "30",
                            "unit": "degC",
                        }
                    ],
                }
            }
        },
    )
    assert replaced["mechanisms"][0]["observations"] == [
        {
            "parameter": "temperature",
            "value": "30",
            "unit": "degC",
        }
    ]


def test_apply_curation_patch_syncs_node_and_mechanism_protein_examples_parity(record):
    base, _ = curate_mod.apply_curation_patch(record, _sample_patch())
    mech_id = base["mechanisms"][0]["id"]
    graph_id = base["causal_graphs"][0]["id"]
    node_id = "gdh_enzyme"

    extra_protein = {
        "uniprot_accession": "UniProtKB:P12345",
        "entry_name": "TEST_GLUOX",
        "protein_name": "Secondary glucose dehydrogenase",
        "gene_symbol": "gdhB",
        "entry_status": "SWISS_PROT",
        "target_organism": {"id": "NCBITaxon:442", "label": "Gluconobacter oxydans"},
        "functional_role": "Secondary periplasmic glucose oxidation.",
        "evidence": [
            {
                "source_ref": "fixture",
                "supports": "support",
                "explanation": "Synthetic node protein grounding.",
            }
        ],
    }

    updated, sections = curate_mod.apply_curation_patch(
        base,
        {
            "node_protein_examples": {
                f"{graph_id}/{node_id}": [extra_protein],
            }
        },
    )
    assert "causal_graphs" in sections
    assert "mechanisms" in sections

    mech_acc = {p["uniprot_accession"] for p in updated["mechanisms"][0]["protein_examples"]}
    node = next(n for n in updated["causal_graphs"][0]["nodes"] if n["id"] == node_id)
    node_acc = {p["uniprot_accession"] for p in node["protein_examples"]}
    assert "UniProtKB:P12345" in node_acc
    assert "UniProtKB:P12345" in mech_acc

    extra_mech_protein = {
        "uniprot_accession": "UniProtKB:Q99999",
        "entry_name": "MECH_GLUOX",
        "protein_name": "Mechanism-added glucose dehydrogenase helper",
        "gene_symbol": "gdhC",
        "entry_status": "TREMBL",
        "target_organism": {"id": "NCBITaxon:442", "label": "Gluconobacter oxydans"},
        "functional_role": "Helper enzyme for glucose oxidation.",
        "evidence": [
            {
                "source_ref": "fixture",
                "supports": "support",
                "explanation": "Synthetic mechanism protein grounding.",
            }
        ],
    }

    updated_from_mech, sections_mech = curate_mod.apply_curation_patch(
        updated,
        {
            "mechanism_protein_examples": {
                mech_id: [extra_mech_protein],
            }
        },
    )
    assert "mechanisms" in sections_mech
    assert "causal_graphs" in sections_mech
    node_after = next(
        n for n in updated_from_mech["causal_graphs"][0]["nodes"] if n["id"] == node_id
    )
    assert "UniProtKB:Q99999" in {p["uniprot_accession"] for p in node_after["protein_examples"]}

